from __future__ import annotations

import csv
import io

import streamlit as st

from bai_ui.branding import AUTHOR, CONTACT_EMAIL, PROVENANCE
from persistence import (
    init_db,
    dashboard_summary,
    concept_summary,
    misconception_summary,
    recent_sessions,
    attempts_for_session,
    export_attempts_rows,
)

from auth import instructor_is_authenticated

if not instructor_is_authenticated():
    st.error("Instructor access required.")
    st.page_link("views/instructor_login.py", label="Go to instructor sign in", icon="🔐")
    st.stop()



init_db()

st.markdown("## ▦ Instructor Mode")
st.caption(PROVENANCE)
st.write(
    "Instructor Mode summarises anonymised learning-process data generated by Model Doctor. "
    "It is designed to show where students struggle, how often hints are needed, which "
    "misconceptions recur, and whether reasoning questions are eventually resolved."
)

st.info(
    "For the prototype, use a pseudonymous Student Code rather than a student name. "
    "The SQLite database is stored locally in `data/bai_datalab.db`."
)

summary = dashboard_summary()

m1, m2, m3, m4, m5 = st.columns(5)
m1.metric("Students", summary["students"])
m2.metric("Sessions", summary["sessions"])
m3.metric("Resolution rate", f'{summary["resolution_rate"]}%')
m4.metric("Attempts", summary["attempts"])
m5.metric("Avg hint level", summary["avg_hint_level"])

st.divider()

left, right = st.columns([1.35, 1], gap="large")

with left:
    st.markdown("### Concepts requiring attention")
    concepts = concept_summary()
    if concepts:
        st.dataframe(concepts, hide_index=True, use_container_width=True)
    else:
        st.caption("No student sessions have been recorded yet.")

with right:
    st.markdown("### Recurring misconceptions")
    misconceptions = misconception_summary()
    if misconceptions:
        st.dataframe(misconceptions, hide_index=True, use_container_width=True)
    else:
        st.caption("No misconceptions have been recorded yet.")

st.divider()
st.markdown("### Recent sessions")
sessions = recent_sessions()

if sessions:
    display_rows=[]
    for row in sessions:
        findings=row.get("findings",0) or 0
        resolved=row.get("resolved",0) or 0
        display_rows.append({
            "Session": row["session_id"][:10],
            "Student code": row["student_code"],
            "Assignment": row["assignment_name"],
            "Strictness": row["strictness"],
            "LLM": row["llm_provider"],
            "Findings": findings,
            "Resolved": resolved,
            "Attempts": row.get("attempts",0),
            "Created": row["created_at"],
        })
    st.dataframe(display_rows, hide_index=True, use_container_width=True)

    session_lookup = {
        f"{r['student_code']} · {r['assignment_name'] or 'Untitled'} · {r['session_id'][:10]}": r["session_id"]
        for r in sessions
    }
    selected = st.selectbox("Inspect a session", list(session_lookup))
    details = attempts_for_session(session_lookup[selected])
    if details:
        st.dataframe(details, hide_index=True, use_container_width=True)
    else:
        st.caption("This session has no submitted reasoning attempts yet.")
else:
    st.caption("No sessions recorded yet. Complete a Model Doctor analysis to populate the dashboard.")

st.divider()
st.markdown("### Research-log export")
st.write(
    "Export attempts as CSV for analysis. The export contains Student Code, not a student name, "
    "plus rule, concept, score, hint level, misconception and response text."
)

rows = export_attempts_rows()
if rows:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=list(rows[0].keys()))
    writer.writeheader()
    writer.writerows(rows)
    st.download_button(
        "Download interaction log (CSV)",
        data=buffer.getvalue(),
        file_name="bai_datalab_interaction_log.csv",
        mime="text/csv",
    )
else:
    st.caption("No attempts are available to export.")

st.divider()
st.caption(f"Developed by {AUTHOR} · Feedback: {CONTACT_EMAIL}")
