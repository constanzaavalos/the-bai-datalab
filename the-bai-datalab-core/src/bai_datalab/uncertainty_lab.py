from __future__ import annotations

from dataclasses import dataclass
import math


@dataclass(frozen=True)
class UncertaintySettings:
    sample_size: int = 300
    noise: float = 0.25
    model_mismatch: float = 0.10
    domain_distance: float = 0.00


@dataclass(frozen=True)
class UncertaintyResult:
    sampling: float
    aleatoric: float
    epistemic: float
    predictive: float
    confidence_width: float
    prediction_width: float
    dominant_component: str
    question: str


def _clip(x: float, lo: float = 0.0, hi: float = 1.5) -> float:
    return max(lo, min(hi, x))


def decompose_uncertainty(settings: UncertaintySettings) -> UncertaintyResult:
    """
    Pedagogical uncertainty decomposition.

    The quantities are dimensionless teaching indices. They are not intended
    to be interpreted as estimator-specific standard errors.
    """
    n_scale = math.sqrt(max(settings.sample_size, 20) / 100.0)

    sampling = 0.30 / n_scale

    aleatoric = (
        0.07
        + 0.50 * settings.noise
    )

    # One reducible part shrinks with n; structural mismatch and OOD distance
    # remain even with large samples.
    reducible_epistemic = 0.18 / n_scale
    structural_epistemic = (
        0.30 * settings.model_mismatch
        + 0.38 * settings.domain_distance
    )
    epistemic = reducible_epistemic + structural_epistemic

    predictive = math.sqrt(
        sampling ** 2
        + aleatoric ** 2
        + epistemic ** 2
    )

    confidence_width = 2.0 * math.sqrt(
        sampling ** 2 + epistemic ** 2
    )
    prediction_width = 2.0 * predictive

    components = {
        "sampling uncertainty": sampling,
        "aleatoric uncertainty": aleatoric,
        "epistemic uncertainty": epistemic,
    }
    dominant = max(components, key=components.get)

    questions = {
        "sampling uncertainty":
            "Would collecting more observations reduce this component? Why?",
        "aleatoric uncertainty":
            "If the outcome remains intrinsically noisy, can simply collecting more observations eliminate this uncertainty?",
        "epistemic uncertainty":
            "Which part of this uncertainty could be reduced by more data, and which part reflects model or domain limitations?",
    }

    return UncertaintyResult(
        sampling=round(_clip(sampling), 4),
        aleatoric=round(_clip(aleatoric), 4),
        epistemic=round(_clip(epistemic), 4),
        predictive=round(_clip(predictive), 4),
        confidence_width=round(_clip(confidence_width, hi=3.0), 4),
        prediction_width=round(_clip(prediction_width, hi=3.0), 4),
        dominant_component=dominant,
        question=questions[dominant],
    )


def more_data_experiment(
    settings: UncertaintySettings,
    multiplier: int = 4,
) -> tuple[UncertaintyResult, UncertaintyResult]:
    before = decompose_uncertainty(settings)

    after_settings = UncertaintySettings(
        sample_size=min(settings.sample_size * multiplier, 20000),
        noise=settings.noise,
        model_mismatch=settings.model_mismatch,
        domain_distance=settings.domain_distance,
    )
    after = decompose_uncertainty(after_settings)

    return before, after


def evaluate_uncertainty_reasoning(
    prompt_type: str,
    answer: str,
) -> tuple[str, str]:
    text = " ".join(answer.lower().split())
    words = len(answer.split())

    if words < 10:
        return (
            "develop",
            "Develop the explanation further. Distinguish the source of uncertainty from the amount of data available.",
        )

    if prompt_type == "more_data":
        sampling_ok = (
            "sampling" in text
            and any(x in text for x in ("decrease", "reduce", "smaller", "shrink"))
        )
        aleatoric_ok = (
            "aleatoric" in text
            and any(x in text for x in ("not", "remain", "irreducible", "noise"))
        )
        epistemic_ok = (
            "epistemic" in text
            and any(x in text for x in ("part", "model", "mismatch", "domain", "reduce"))
        )

        if sampling_ok and aleatoric_ok and epistemic_ok:
            return (
                "resolved",
                "Your explanation distinguishes uncertainty that shrinks with information from uncertainty generated by irreducible noise and structural/model limitations.",
            )

        return (
            "develop",
            "Separate the components explicitly: what happens to sampling uncertainty, irreducible outcome noise, and model/domain uncertainty when n increases?",
        )

    if prompt_type == "prediction_interval":
        if (
            "aleatoric" in text
            and any(x in text for x in ("prediction", "individual", "future", "new observation"))
            and any(x in text for x in ("confidence", "mean", "parameter"))
        ):
            return (
                "resolved",
                "You correctly distinguish uncertainty about an estimated mean/model quantity from uncertainty in a new individual outcome.",
            )

        return (
            "develop",
            "Compare uncertainty about an estimated mean response with uncertainty about a future individual observation. Which one must also include outcome noise?",
        )

    if prompt_type == "ood":
        if (
            any(x in text for x in ("domain", "distribution", "out-of-distribution", "ood", "extrapolat"))
            and "epistemic" in text
        ):
            return (
                "resolved",
                "You identified domain distance as a source of epistemic uncertainty: the model has less evidence supporting predictions away from its training experience.",
            )

        return (
            "develop",
            "Focus on what the model has learned from its training domain. Why should predictions farther from that domain carry additional epistemic uncertainty?",
        )

    return (
        "develop",
        "Use the uncertainty decomposition explicitly in your explanation.",
    )
